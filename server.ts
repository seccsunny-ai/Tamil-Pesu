import express from "express";
import path from "path";
import { fileURLToPath } from "url";
import dotenv from "dotenv";
import { GoogleGenAI } from "@google/genai";

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const app = express();
const PORT = process.env.PORT || 3000;

app.use(express.json({ limit: "50mb" }));
app.use(express.urlencoded({ extended: true, limit: "50mb" }));

// Initialize Google Gemini SDK on the server
const ai = new GoogleGenAI({
  apiKey: process.env.GEMINI_API_KEY,
  httpOptions: {
    headers: {
      "User-Agent": "aistudio-build",
    },
  },
});

// API Routes
app.get("/api/health", (_req, res) => {
  res.json({
    status: "ok",
    hasApiKey: Boolean(process.env.GEMINI_API_KEY),
    time: new Date().toISOString(),
  });
});

/**
 * Text-to-Speech Endpoint using Gemini 3.8 Flash Lite TTS
 * Synthesizes authentic spoken Tamil pronunciation
 */
app.post("/api/speak-tts", async (req, res) => {
  try {
    const { text, voiceName = "Kore", speakerStyle = "Warm, natural native South Indian Tamil speaker" } = req.body;

    if (!text || typeof text !== "string") {
      return res.status(400).json({ error: "Missing 'text' in request body" });
    }

    if (!process.env.GEMINI_API_KEY) {
      return res.status(503).json({
        error: "GEMINI_API_KEY is not configured. Please add it to your environment secrets.",
      });
    }

    // Call gemini-3.8-flash-lite-tts for natural spoken Tamil voice synthesis
    const response = await ai.models.generateContent({
      model: "gemini-3.8-flash-lite-tts",
      contents: [
        {
          role: "user",
          parts: [
            {
              text: text,
              speechMetadata: {
                style: speakerStyle,
              },
            },
          ],
        },
      ],
      config: {
        responseModalities: ["AUDIO"],
        speechConfig: {
          voiceConfig: {
            prebuiltVoiceConfig: { voiceName: voiceName },
          },
        },
      },
    });

    const base64Audio = response.candidates?.[0]?.content?.parts?.[0]?.inlineData?.data;
    const mimeType = response.candidates?.[0]?.content?.parts?.[0]?.inlineData?.mimeType || "audio/wav";

    if (!base64Audio) {
      return res.status(500).json({ error: "No audio generated by the model" });
    }

    res.json({
      audioBase64: base64Audio,
      mimeType,
    });
  } catch (error: any) {
    console.error("Error in /api/speak-tts:", error);
    res.status(500).json({
      error: error.message || "Failed to generate speech audio",
    });
  }
});

/**
 * Speech Evaluation Endpoint
 * Multimodal analysis of user's audio recording comparing against target Spoken Tamil phrase
 */
app.post("/api/evaluate-speech", async (req, res) => {
  try {
    const { audioBase64, mimeType = "audio/webm", targetPhrase, expectedPhonetics, context = "" } = req.body;

    if (!audioBase64 || !targetPhrase) {
      return res.status(400).json({ error: "Missing audioBase64 or targetPhrase" });
    }

    if (!process.env.GEMINI_API_KEY) {
      return res.status(503).json({
        error: "GEMINI_API_KEY is not configured in environment.",
      });
    }

    const audioPart = {
      inlineData: {
        mimeType: mimeType.split(";")[0], // Clean mime type (e.g., 'audio/webm' or 'audio/wav')
        data: audioBase64,
      },
    };

    const prompt = `You are an expert native South Indian Tamil linguistics and pronunciation coach based on the teaching methodologies of Dr. D. Renganathan, Prof. M. Shanmugam Pillai, and CIIL Mysore.
You are evaluating an audio recording from an adult student practicing Spoken Tamil.

TARGET COLLOQUIAL PHRASE: "${targetPhrase}"
EXPECTED PHONETICS: "${expectedPhonetics || targetPhrase}"
SCENARIO / CONTEXT: "${context}"

Carefully listen to the student's pronunciation in the audio.
Analyze specifically:
1. Overall accuracy score (integer 0 to 100).
2. Spoken Transcript: what the student actually said (in Romanized phonetic Tamil).
3. South Indian Phoneme Breakdown:
   - Retroflex consonants (like 'zh'/'ḻ' in Tamizh, retroflex 'ṭ'/'d', 'ṇ', 'ḷ')
   - Double consonants / geminates (e.g. 'kk', 'tt', 'pp', 'cc', 'nn')
   - Vowel duration (short 'a', 'e', 'o' vs elongated 'aa', 'ee', 'oo')
   - Colloquial endings and sandhi (e.g., '-tu' becoming '-du' or dropping 'r' -> 'avaru')
4. Encouragement / praise (include a friendly native touch like 'Romba nalladhu!' or 'Super-aa sonniinga!').
5. Coaching Tip: 1-2 actionable, concise tips to sound more like a natural native speaker.

You MUST respond strictly with valid JSON with this exact structure:
{
  "score": 85,
  "spokenTranscript": "...",
  "accuracyRating": "Excellent" | "Good" | "Needs Practice",
  "phonemeFeedback": [
    {
      "sound": "Retroflex zh (ழ)",
      "status": "perfect" | "acceptable" | "needs_work",
      "note": "..."
    },
    {
      "sound": "Geminate plosive (kk / pp / tt)",
      "status": "perfect" | "acceptable" | "needs_work",
      "note": "..."
    },
    {
      "sound": "Vowel Length (Short vs Long)",
      "status": "perfect" | "acceptable" | "needs_work",
      "note": "..."
    }
  ],
  "praise": "...",
  "coachingTip": "..."
}`;

    const response = await ai.models.generateContent({
      model: "gemini-3.8-flash",
      contents: {
        parts: [audioPart, { text: prompt }],
      },
      config: {
        responseMimeType: "application/json",
        temperature: 0.2,
      },
    });

    const responseText = response.text || "{}";
    const cleanJson = responseText.replace(/```json\n?/g, "").replace(/```\n?/g, "").trim();
    const evaluation = JSON.parse(cleanJson);

    res.json(evaluation);
  } catch (error: any) {
    console.error("Error in /api/evaluate-speech:", error);
    res.status(500).json({
      error: error.message || "Failed to analyze speech audio",
    });
  }
});

/**
 * Interactive Colloquial Tamil Roleplay Partner
 */
app.post("/api/roleplay-chat", async (req, res) => {
  try {
    const { scenarioId, scenarioTitle, partnerRole, userRole, history, message } = req.body;

    if (!process.env.GEMINI_API_KEY) {
      return res.status(503).json({
        error: "GEMINI_API_KEY is not configured.",
      });
    }

    const systemInstruction = `You are a conversational Spoken Tamil language partner roleplaying a realistic South Indian daily situation.
Scenario: ${scenarioTitle || "Everyday conversation"}
Your Role: ${partnerRole || "Native shopkeeper/friend/doctor"}
User's Role: ${userRole || "Student/Customer/Visitor"}

CRITICAL RULES:
1. Speak ONLY in authentic, colloquial South Indian Spoken Tamil (NOT formal literary literary book Tamil).
   - Use colloquial verb endings (-re, -om, -aange, -aachu, -kitta, -ileruntu, -nnu).
   - Use natural fillers and honorifics (e.g. 'vaanga', 'aamaa', 'cari', 'ennaappa', 'appadiyannaa').
2. ALWAYS provide the Romanized phonetic transcription (e.g. "Vāṅga thambi, enna vēṇum?").
3. DO NOT output Tamil script in this mode (user specified Romanized phonetic script only for rapid fluency).
4. Provide the exact English translation.
5. Provide a brief "Coaching Note" explaining any cultural nuance or colloquial grammar used in this turn.
6. Provide 2 suggested natural replies that the learner could say next (with English translation).

Return valid JSON:
{
  "tamilSpoken": "Romanized phonetic Tamil sentence",
  "englishTranslation": "English meaning",
  "culturalNote": "Brief insight on the colloquial phrase",
  "suggestedReplies": [
    { "tamil": "...", "english": "..." },
    { "tamil": "...", "english": "..." }
  ]
}`;

    const formattedHistory = (history || []).map((msg: any) => ({
      role: msg.role === "user" ? "user" : "model",
      parts: [{ text: msg.text }],
    }));

    const response = await ai.models.generateContent({
      model: "gemini-3.8-flash",
      contents: [
        ...formattedHistory,
        {
          role: "user",
          parts: [{ text: message || "Vanakkam! (I am starting the conversation)" }],
        },
      ],
      config: {
        systemInstruction,
        responseMimeType: "application/json",
        temperature: 0.7,
      },
    });

    const responseText = response.text || "{}";
    const cleanJson = responseText.replace(/```json\n?/g, "").replace(/```\n?/g, "").trim();
    const data = JSON.parse(cleanJson);

    res.json(data);
  } catch (error: any) {
    console.error("Error in /api/roleplay-chat:", error);
    res.status(500).json({ error: error.message || "Failed to process roleplay turn" });
  }
});

// Setup Vite middleware in dev or static files in production
async function startServer() {
  if (process.env.NODE_ENV !== "production") {
    const { createServer: createViteServer } = await import("vite");
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: "spa",
    });
    app.use(vite.middlewares);
  } else {
    app.use(express.static(path.resolve(__dirname, "dist")));
    app.get("*", (_req, res) => {
      res.sendFile(path.resolve(__dirname, "dist", "index.html"));
    });
  }

  app.listen(PORT, () => {
    console.log(`Tamizhppēcu server running on http://localhost:${PORT}`);
  });
}

startServer();
